"""Generate the SYNTHETIC knowledge corpus and retrieval queries (one-off, output committed).

Everything here is invented. Nothing comes from a real company, customer or
ticket system. It is generated by an LLM from the taxonomy below so the
retrieval evaluation has a realistic, messy-language corpus to search.

Leakage control: queries are generated in a SEPARATE call that sees only the
symptom brief of a category, never any ticket text, so a query can't simply
copy a ticket's wording. Relevance is by root-cause label, not by text.

    COPILOT_LLM_MODE=live python scripts/generate_corpus.py
"""
from __future__ import annotations

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from copilot.llm import Gemini  # noqa: E402

OUT = ROOT / "corpus"
MODEL = "gemini-3.5-flash-lite"
TICKETS_PER_CATEGORY = 7
QUERIES_PER_CATEGORY = 3

# category: (symptom brief, root cause + fix seed). The first 8 are the ones the
# demo cluster can reproduce; the rest are realistic distractors, several of them
# deliberate look-alikes (rate limit vs bad tag, liveness vs readiness, eviction vs OOM).
TAXONOMY = {
    "image_pull_error": ("New pods never start; status shows ErrImagePull / ImagePullBackOff right after a deploy.",
                         "The deployment references an image tag or repository that does not exist (typo, unpushed build). Fix: roll back to the previous revision, then fix the tag in CI."),
    "crashloop_config_error": ("Pods restart over and over (CrashLoopBackOff) right after a config or env change.",
                               "A configuration value fails the application's startup validation, so the process exits with code 1. Fix: roll back the config change; read logs --previous to find the bad key."),
    "readiness_probe_failure": ("Pods are Running but never become Ready; the rollout stalls; the Service has fewer endpoints.",
                                "The readiness probe points at the wrong path/port or a check that can't pass. Fix: roll back or correct the probe spec."),
    "oom_killed": ("Containers restart with exit code 137; memory graphs hit the limit just before.",
                   "The container exceeds its memory limit and the kernel OOM-kills it (often after a cache-size or batch-size change). Fix: revert the change or raise the memory limit."),
    "missing_secret": ("New pods are stuck in CreateContainerConfigError after a restart or deploy; old pods still serve.",
                       "A Secret (or key) referenced by the pod spec was deleted or renamed, e.g. by a rotation job. Fix: restore the Secret from the secret manager (human step), then pods start."),
    "service_selector_mismatch": ("Clients get connection refused / 503 from a Service even though all pods are Running and Ready.",
                                  "The Service selector doesn't match the pod labels (label rename or typo), so it has zero endpoints. Fix: correct the selector to the pods' labels."),
    "cpu_throttling": ("Latency rises sharply, probes time out intermittently, but there are no errors in logs and CPU usage looks flat.",
                       "The CPU limit is too low, so CFS throttles the container (high nr_throttled). Fix: raise or remove the CPU limit, or revert the change that lowered it."),
    "dependency_timeout": ("One service returns 504s and logs upstream timeouts while its own pods look healthy.",
                           "A downstream dependency became slow after its own deploy (or degraded), so callers time out. Fix: roll back the dependency; tune timeouts/circuit breakers."),
    "config_regression": ("Right after a config change the service starts and passes health checks, but a feature fails on every request (errors in logs, 5xx to callers).",
                          "A configuration value is wrong but valid enough not to crash the process (typo in a hostname/URL/port, wrong feature flag). Fix: roll back the config change, add validation."),
    "registry_rate_limit": ("Image pulls fail intermittently across many nodes with 429 Too Many Requests.",
                            "Anonymous pulls hit the registry's rate limit (e.g. Docker Hub). Fix: authenticated pulls via imagePullSecrets or a pull-through mirror."),
    "liveness_probe_restart_loop": ("Pods get killed and restarted every few minutes during startup or under load; events show liveness probe failures.",
                                    "The liveness probe is too aggressive for a slow-starting or busy app, so the kubelet kills healthy containers. Fix: add a startupProbe, raise thresholds."),
    "node_disk_pressure_eviction": ("Many pods on one node show Evicted; node condition DiskPressure.",
                                    "The node's disk filled (images, logs, emptyDir), so the kubelet evicts pods. Fix: clean up images/logs, add disk, set ephemeral-storage limits."),
    "network_policy_block": ("Calls between two services time out after a security change; DNS resolves fine.",
                             "A NetworkPolicy now denies the traffic (default-deny without an allow rule). Fix: add the allow rule."),
    "dns_resolution_failure": ("Intermittent 'no such host' / 'i/o timeout' resolving service names cluster-wide.",
                               "CoreDNS is overloaded or crashing (or ndots causes lookup storms). Fix: scale CoreDNS, enable NodeLocal DNSCache, tune ndots."),
    "tls_cert_expired": ("Clients suddenly fail with x509: certificate has expired or is not yet valid.",
                         "A TLS certificate expired because renewal (cert-manager / manual) failed. Fix: renew the certificate, fix the issuer."),
    "pvc_mount_failure": ("Pods stuck in ContainerCreating with FailedMount / FailedAttachVolume / Multi-Attach errors.",
                          "A ReadWriteOnce volume is still attached to another node, or the CSI driver is unhealthy. Fix: detach from the old node / fix the CSI driver."),
    "gpu_xid_error": ("GPU jobs fail or stay Pending; one node reports fewer allocatable GPUs; dmesg shows NVIDIA Xid errors.",
                      "A GPU on the node faulted (e.g. Xid 79 fell off the bus) and the device plugin marked it unhealthy. Fix: cordon and drain the node, reset or RMA the GPU."),
    "nccl_timeout": ("A multi-node training job hangs and then fails with an NCCL watchdog timeout.",
                     "A flapping InfiniBand/RoCE link or one bad node stalls collective ops. Fix: run nccl-tests to find the bad node, cordon it, restart the job from checkpoint."),
    "node_not_ready": ("A node goes NotReady; its pods show Unknown/Terminating and get rescheduled slowly.",
                       "The kubelet stopped posting status (kubelet crash, network partition, memory exhaustion on the node). Fix: investigate the node, drain and repair."),
    "resource_quota_exceeded": ("A Deployment's new ReplicaSet creates no pods; events show FailedCreate 'exceeded quota'.",
                                "The namespace ResourceQuota is exhausted. Fix: raise the quota or reduce requests."),
    "pdb_blocking_drain": ("A node drain or cluster upgrade hangs; eviction keeps being refused.",
                           "A PodDisruptionBudget allows zero disruptions (minAvailable equals replicas). Fix: scale up or adjust the PDB temporarily."),
    "pending_insufficient_resources": ("Pods stay Pending with FailedScheduling: Insufficient cpu / memory / nvidia.com/gpu.",
                                       "Requests exceed free capacity on every node (or node selectors/taints exclude capacity). Fix: right-size requests, add capacity."),
}

TICKET_SCHEMA = {
    "type": "array",
    "items": {
        "type": "object",
        "properties": {
            "title": {"type": "string"},
            "service": {"type": "string"},
            "reported_symptoms": {"type": "string"},
            "investigation": {"type": "string"},
            "root_cause": {"type": "string"},
            "resolution": {"type": "string"},
        },
        "required": ["title", "service", "reported_symptoms", "investigation", "root_cause", "resolution"],
    },
}

TICKET_PROMPT = """You are writing SYNTHETIC historical support tickets for an internal knowledge base at a
GPU cloud provider that runs customer workloads on Kubernetes. They will be used to test a search system.

Root-cause category (for you only): {cat}
What it looks like: {symptoms}
What it actually is and the usual fix: {cause}

Write {n} different resolved tickets for this category. Make them read like real tickets written by
different support engineers:
- different services and customers (inference APIs, training jobs, vector databases, batch ETL, web backends...)
- "reported_symptoms": the customer's first report, in their words, often vague, sometimes a wrong guess
- "investigation": what the engineer checked, with 1-3 realistic snippets (kubectl output, log lines, metrics)
- "root_cause" and "resolution": short, specific, as the engineer recorded them
- vary vocabulary; do NOT reuse the same phrases across tickets; 90-170 words per ticket total
- invent all names; no real company names; no real people."""

RUNBOOK_PROMPT = """Write a concise SYNTHETIC on-call runbook (markdown, 180-280 words) for this Kubernetes failure mode at a
GPU cloud provider. Sections: Symptoms, Checks (kubectl commands with one line each on what to look for),
Likely causes, Remediation, When to escalate. No real company names.

Failure mode: {cat}
What it looks like: {symptoms}
What it actually is and the usual fix: {cause}"""

QUERY_PROMPT = """Write {n} different first reports of a production problem, as they would arrive at a support
team. The reporter does NOT know the cause. Base them ONLY on this observed behaviour:

"{symptoms}"

Make the three different in voice: (1) a customer ticket, (2) a terse on-call chat message, (3) an alert
summary or a paste of 1-2 lines of output. 15-60 words each. Do not name the root cause. Invent names.
Return a JSON array of strings."""


def main() -> None:
    only = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None
    if only:  # add one category to the existing corpus (used when config_regression was added)
        return append_category(only)
    llm = Gemini(MODEL, mode="live", tag="corpus")
    gen = {"temperature": 1.0, "responseMimeType": "application/json"}
    rng = random.Random(7)
    tickets, runbooks, queries = [], [], []
    for cat, (symptoms, cause) in TAXONOMY.items():
        print("generating", cat, file=sys.stderr)
        r = llm.generate({
            "contents": [{"role": "user", "parts": [{"text": TICKET_PROMPT.format(
                cat=cat, symptoms=symptoms, cause=cause, n=TICKETS_PER_CATEGORY)}]}],
            "generationConfig": {**gen, "responseSchema": TICKET_SCHEMA},
        })
        for t in json.loads(r.text):
            tickets.append({**t, "category": cat})
        r = llm.generate({
            "contents": [{"role": "user", "parts": [{"text": RUNBOOK_PROMPT.format(cat=cat, symptoms=symptoms, cause=cause)}]}],
            "generationConfig": {"temperature": 0.7},
        })
        runbooks.append({"id": f"RB-{cat.replace('_', '-')}", "category": cat, "text": r.text.strip()})
        r = llm.generate({
            "contents": [{"role": "user", "parts": [{"text": QUERY_PROMPT.format(symptoms=symptoms, n=QUERIES_PER_CATEGORY)}]}],
            "generationConfig": {**gen, "responseSchema": {"type": "array", "items": {"type": "string"}}},
        })
        for i, q in enumerate(json.loads(r.text)[:QUERIES_PER_CATEGORY]):
            queries.append({"query": q, "category": cat, "split": "dev" if i == 0 else "test"})
    rng.shuffle(tickets)  # ticket IDs must not leak the category
    for i, t in enumerate(tickets):
        t["id"] = f"T-{1001 + i}"
    rng.shuffle(queries)
    for i, q in enumerate(queries):
        q["id"] = f"Q-{i + 1:03d}"
    OUT.mkdir(exist_ok=True)
    with (OUT / "tickets.jsonl").open("w") as f:
        for t in tickets:
            f.write(json.dumps({"id": t["id"], "synthetic": True, **{k: v for k, v in t.items() if k != "id"}}) + "\n")
    (OUT / "runbooks").mkdir(exist_ok=True)
    for rb in runbooks:
        (OUT / "runbooks" / f"{rb['id']}.md").write_text(
            f"<!-- SYNTHETIC runbook. id: {rb['id']} category: {rb['category']} -->\n{rb['text']}\n")
    with (ROOT / "eval" / "retrieval_queries.jsonl").open("w") as f:
        for q in queries:
            f.write(json.dumps(q) + "\n")
    print(f"{len(tickets)} tickets, {len(runbooks)} runbooks, {len(queries)} queries", file=sys.stderr)


def append_category(cat: str) -> None:
    llm = Gemini(MODEL, mode="live", tag="corpus")
    symptoms, cause = TAXONOMY[cat]
    gen = {"temperature": 1.0, "responseMimeType": "application/json"}
    existing = [json.loads(x) for x in (OUT / "tickets.jsonl").read_text().splitlines()]
    r = llm.generate({"contents": [{"role": "user", "parts": [{"text": TICKET_PROMPT.format(
        cat=cat, symptoms=symptoms, cause=cause, n=TICKETS_PER_CATEGORY)}]}],
        "generationConfig": {**gen, "responseSchema": TICKET_SCHEMA}})
    with (OUT / "tickets.jsonl").open("a") as f:
        for i, t in enumerate(json.loads(r.text)):
            f.write(json.dumps({"id": f"T-{1001 + len(existing) + i}", "synthetic": True, **t, "category": cat}) + "\n")
    r = llm.generate({"contents": [{"role": "user", "parts": [{"text": RUNBOOK_PROMPT.format(
        cat=cat, symptoms=symptoms, cause=cause)}]}], "generationConfig": {"temperature": 0.7}})
    rb = f"RB-{cat.replace('_', '-')}"
    (OUT / "runbooks" / f"{rb}.md").write_text(f"<!-- SYNTHETIC runbook. id: {rb} category: {cat} -->\n{r.text.strip()}\n")
    r = llm.generate({"contents": [{"role": "user", "parts": [{"text": QUERY_PROMPT.format(
        symptoms=symptoms, n=QUERIES_PER_CATEGORY)}]}],
        "generationConfig": {**gen, "responseSchema": {"type": "array", "items": {"type": "string"}}}})
    qpath = ROOT / "eval" / "retrieval_queries.jsonl"
    n = len(qpath.read_text().splitlines())
    with qpath.open("a") as f:
        for i, q in enumerate(json.loads(r.text)[:QUERIES_PER_CATEGORY]):
            f.write(json.dumps({"query": q, "category": cat, "split": "dev" if i == 0 else "test",
                                "id": f"Q-{n + i + 1:03d}"}) + "\n")


if __name__ == "__main__":
    main()
